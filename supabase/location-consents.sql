create table if not exists public.location_consents (
  id bigint generated by default as identity primary key,
  visitor_id text not null unique,
  ip_address text,
  country text,
  region text,
  city text,
  gps_latitude double precision not null,
  gps_longitude double precision not null,
  gps_accuracy double precision,
  consented_at timestamptz not null default now(),
  display_name text,
  notes text,
  constraint location_consents_latitude_range check (gps_latitude between -90 and 90),
  constraint location_consents_longitude_range check (gps_longitude between -180 and 180)
);
alter table public.location_consents enable row level security;

drop policy if exists "Public can add location consent records" on public.location_consents;
create policy "Public can add location consent records" on public.location_consents
for insert to anon with check (gps_latitude between -90 and 90 and gps_longitude between -180 and 180);

drop policy if exists "Authenticated admins can view location consent records" on public.location_consents;
create policy "Authenticated admins can view location consent records" on public.location_consents
for select to authenticated using (true);

drop policy if exists "Authenticated admins can update location consent records" on public.location_consents;
create policy "Authenticated admins can update location consent records" on public.location_consents
for update to authenticated using (true) with check (true);

drop policy if exists "Authenticated admins can delete location consent records" on public.location_consents;
create policy "Authenticated admins can delete location consent records" on public.location_consents
for delete to authenticated using (true);

insert into public.location_consents (
  visitor_id, ip_address, country, region, city, gps_latitude, gps_longitude, gps_accuracy, consented_at
)
select distinct on (visitor_id)
  visitor_id, ip_address, country, region, city, gps_latitude, gps_longitude, gps_accuracy,
  coalesce(gps_consent_at, created_at)
from public.visitor_logs
where gps_latitude is not null and gps_longitude is not null
order by visitor_id, created_at desc
on conflict (visitor_id) do nothing;


-- The browser checks only whether its own random visitor cookie has an active consent record.
create or replace function public.has_location_consent(p_visitor_id text)
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.location_consents
    where visitor_id = p_visitor_id
  );
$$;
revoke all on function public.has_location_consent(text) from public;
grant execute on function public.has_location_consent(text) to anon, authenticated;
