create table if not exists public.visitor_logs (
  id bigint generated by default as identity primary key,
  visitor_id text not null,
  ip_address text,
  country text,
  region text,
  city text,
  device text,
  operating_system text,
  browser text,
  user_agent text,
  page_path text not null,
  created_at timestamptz not null default now()
);

create index if not exists visitor_logs_created_at_idx on public.visitor_logs (created_at desc);
create index if not exists visitor_logs_page_path_idx on public.visitor_logs (page_path);
create index if not exists visitor_logs_visitor_id_idx on public.visitor_logs (visitor_id);

alter table public.visitor_logs enable row level security;

drop policy if exists "Public can record visitor logs" on public.visitor_logs;
create policy "Public can record visitor logs"
on public.visitor_logs for insert
to anon, authenticated
with check (true);

drop policy if exists "Authenticated users can read visitor logs" on public.visitor_logs;
create policy "Authenticated users can read visitor logs"
on public.visitor_logs for select
to authenticated
using (true);
